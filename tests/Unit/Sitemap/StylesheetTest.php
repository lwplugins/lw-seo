<?php
/**
 * Stylesheet unit tests.
 *
 * @package LightweightPlugins\SEO
 */

declare(strict_types=1);

namespace LightweightPlugins\SEO\Tests\Unit\Sitemap;

use LightweightPlugins\SEO\Sitemap\Stylesheet;
use LightweightPlugins\SEO\Tests\Unit\MonkeyTestCase;

/**
 * @covers \LightweightPlugins\SEO\Sitemap\Stylesheet
 */
final class StylesheetTest extends MonkeyTestCase {

	public function test_xsl_contains_urlset_and_index_templates(): void {
		$xsl = Stylesheet::xsl();

		$this->assertStringContainsString( 'match="sitemap:urlset"', $xsl );
		$this->assertStringContainsString( 'match="sitemap:sitemapindex"', $xsl );
		$this->assertStringContainsString( 'This XML sitemap is for search engines. Generated by LW SEO.', $xsl );
	}

	public function test_xsl_is_well_formed(): void {
		$doc = new \DOMDocument();

		$this->assertTrue( $doc->loadXML( Stylesheet::xsl() ) );
	}
}
