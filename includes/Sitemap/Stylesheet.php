<?php
/**
 * Browser-readable view of the XML sitemap (XSL).
 *
 * @package LightweightPlugins\SEO
 */

declare(strict_types=1);

namespace LightweightPlugins\SEO\Sitemap;

/**
 * Serves /sitemap.xsl, the stylesheet the sitemap XML links to.
 */
final class Stylesheet {

	/**
	 * Path of the stylesheet relative to the site root.
	 */
	public const URL_PATH = 'sitemap.xsl';

	/**
	 * Query var set by the rewrite rule.
	 */
	private const QUERY_VAR = 'lw_sitemap_xsl';

	/**
	 * The stylesheet: a sitemap index list and a urlset table, inline CSS only.
	 */
	private const XSL = <<<'XSL'
<?xml version="1.0" encoding="UTF-8"?>
<xsl:stylesheet version="1.0"
	xmlns:xsl="http://www.w3.org/1999/XSL/Transform"
	xmlns:sitemap="http://www.sitemaps.org/schemas/sitemap/0.9"
	xmlns:image="http://www.google.com/schemas/sitemap-image/1.1"
	exclude-result-prefixes="sitemap image">
<xsl:output method="html" version="1.0" encoding="UTF-8" indent="yes"/>

<xsl:template match="sitemap:sitemapindex">
	<html lang="en">
		<xsl:call-template name="page">
			<xsl:with-param name="title">XML Sitemap Index</xsl:with-param>
			<xsl:with-param name="body">
				<table>
					<thead><tr><th>Sitemap</th><th>Last modified</th></tr></thead>
					<tbody>
						<xsl:for-each select="sitemap:sitemap">
							<tr>
								<td><a href="{sitemap:loc}"><xsl:value-of select="sitemap:loc"/></a></td>
								<td><xsl:value-of select="sitemap:lastmod"/></td>
							</tr>
						</xsl:for-each>
					</tbody>
				</table>
			</xsl:with-param>
		</xsl:call-template>
	</html>
</xsl:template>

<xsl:template match="sitemap:urlset">
	<html lang="en">
		<xsl:call-template name="page">
			<xsl:with-param name="title">XML Sitemap</xsl:with-param>
			<xsl:with-param name="body">
				<table>
					<thead><tr><th>URL</th><th>Images</th><th>Last modified</th></tr></thead>
					<tbody>
						<xsl:for-each select="sitemap:url">
							<tr>
								<td><a href="{sitemap:loc}"><xsl:value-of select="sitemap:loc"/></a></td>
								<td><xsl:value-of select="count(image:image)"/></td>
								<td><xsl:value-of select="sitemap:lastmod"/></td>
							</tr>
						</xsl:for-each>
					</tbody>
				</table>
			</xsl:with-param>
		</xsl:call-template>
	</html>
</xsl:template>

<xsl:template name="page">
	<xsl:param name="title"/>
	<xsl:param name="body"/>
	<head>
		<meta charset="UTF-8"/>
		<meta name="viewport" content="width=device-width, initial-scale=1"/>
		<meta name="robots" content="noindex"/>
		<title><xsl:value-of select="$title"/></title>
		<style>
			body { font: 16px/1.5 -apple-system, "Segoe UI", Roboto, sans-serif; color: #1d2327; margin: 0; padding: 32px 16px; background: #f6f7f7; }
			main { max-width: 960px; margin: 0 auto; }
			h1 { font-size: 24px; margin: 0 0 8px; }
			p { margin: 0 0 24px; color: #50575e; }
			table { width: 100%; border-collapse: collapse; background: #fff; border: 1px solid #dcdcde; }
			th, td { text-align: left; padding: 10px 14px; border-bottom: 1px solid #f0f0f1; word-break: break-all; }
			th { background: #f6f7f7; font-weight: 600; }
			a { color: #2271b1; text-decoration: none; }
			a:hover { text-decoration: underline; }
		</style>
	</head>
	<body>
		<main>
			<h1><xsl:value-of select="$title"/></h1>
			<p>This XML sitemap is for search engines. Generated by LW SEO.</p>
			<xsl:copy-of select="$body"/>
		</main>
	</body>
</xsl:template>

</xsl:stylesheet>
XSL;

	/**
	 * Hook the rewrite rule, query var and request handler.
	 *
	 * @return void
	 */
	public static function register(): void {
		add_action( 'init', [ self::class, 'add_rewrite_rule' ] );
		add_filter( 'query_vars', [ self::class, 'add_query_var' ] );
		add_action( 'template_redirect', [ self::class, 'serve' ] );
	}

	/**
	 * Register the /sitemap.xsl rewrite rule.
	 *
	 * @return void
	 */
	public static function add_rewrite_rule(): void {
		add_rewrite_rule( '^sitemap\.xsl$', 'index.php?' . self::QUERY_VAR . '=1', 'top' );
	}

	/**
	 * Register the query var.
	 *
	 * @param array<string> $vars Query vars.
	 * @return array<string>
	 */
	public static function add_query_var( array $vars ): array {
		$vars[] = self::QUERY_VAR;

		return $vars;
	}

	/**
	 * Send the stylesheet on a /sitemap.xsl request.
	 *
	 * @return void
	 */
	public static function serve(): void {
		if ( '' === (string) get_query_var( self::QUERY_VAR ) ) {
			return;
		}

		header( 'Content-Type: text/xsl; charset=UTF-8' );
		header( 'X-Robots-Tag: noindex' );

		echo self::xsl(); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- static XSL constant, no user input.
		exit;
	}

	/**
	 * The stylesheet source.
	 *
	 * @return string
	 */
	public static function xsl(): string {
		return self::XSL;
	}
}
